function interviewStep(title, question) {
  return {
    title,
    question,
    label: question,
    instruction: '围绕“' + title + '”像咨询师一样听取用户原话；信息不清楚时聚焦一个主题，最多补 2–3 个短确认点，并给出可参考的方向。',
    why: '帮助理解用户在这一主题上的真实情况。',
    type: 'text',
    conversation: true
  };
}

function steps(items) {
  return items.map((item) => interviewStep(item[0], item[1]));
}

