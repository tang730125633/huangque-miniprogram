function interviewStep(title, question) {
  return {
    title,
    question,
    label: question,
    instruction: '围绕“' + title + '”听取用户原话；信息不清楚时只追问一个点。',
    why: '这是内部采访提纲的一项，客户只需要自然回答。',
    type: 'text',
    conversation: true
  };
}

function steps(items) {
  return items.map((item) => interviewStep(item[0], item[1]));
}

